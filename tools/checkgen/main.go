package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v2"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	data, err := os.ReadFile("config.yml")
	if err != nil {
		return err
	}
	var config struct {
		Checks map[string]string `yaml:"checks"`
	}
	if err := yaml.UnmarshalStrict(data, &config); err != nil {
		return err
	}
	if len(config.Checks) == 0 {
		return fmt.Errorf("config.yml has no checks")
	}
	names := make([]string, 0, len(config.Checks))
	for name := range config.Checks {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		path := config.Checks[name]
		if !strings.HasPrefix(path, "github.com/scorify/scorify/pkg/localchecks/") || strings.Contains(path, "@") {
			return fmt.Errorf("check %q must use a local implementation", name)
		}
		if _, err := os.Stat(filepath.Join("pkg/localchecks", strings.TrimPrefix(path, "github.com/scorify/scorify/pkg/localchecks/"), "main.go")); err != nil {
			return fmt.Errorf("check %q: %w", name, err)
		}
		source := fmt.Sprintf(`// Code generated by tools/checkgen; DO NOT EDIT.
package checks

import (
	"github.com/scorify/schema"
	check %q
)

func init() {
	fields, err := schema.Describe(check.Schema{})
	if err != nil { panic(err) }
	Checks[%q] = Check{Func: check.Run, Validate: check.Validate, Schema: fields}
}
`, path, name)
		formatted, err := format.Source([]byte(source))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join("pkg/checks", name+".go"), formatted, 0644); err != nil {
			return err
		}
	}
	return nil
}
